-- 1. Tabla de fincas
create table if not exists public.fincas (
    id              bigint generated by default as identity primary key,
    nombre          text    not null check (char_length(trim(nombre)) >= 3),
    descripcion     text    not null default 'Finca agregada recientemente al catálogo.',
    precio_noche    integer not null check (precio_noche > 0),
    precio_dia_sol  integer not null check (precio_dia_sol > 0),
    categoria       text    not null,
    cantidad        integer not null check (cantidad >= 0),
    cupo_maximo     integer not null check (cupo_maximo > 0),
    calificacion    numeric(2,1) not null default 0 check (calificacion between 0 and 5),
    resenas         integer not null default 0 check (resenas >= 0),
    imagen          text    not null,
    imagenes        jsonb   not null default '[]'::jsonb,
    creada_en       timestamptz not null default now(),
    -- Regla del negocio: el día de sol no puede costar más que la noche
    constraint dia_sol_no_mayor_que_noche check (precio_dia_sol <= precio_noche)
);

-- No se permiten nombres repetidos (sin importar mayúsculas)
create unique index if not exists fincas_nombre_unico on public.fincas (lower(nombre));

-- 2. Tabla de reservas
create table if not exists public.reservas (
    id             bigint generated always as identity primary key,
    finca_id       bigint references public.fincas(id) on delete set null,
    finca_nombre   text    not null,
    nombre         text    not null check (char_length(trim(nombre)) >= 3),
    correo         text    not null,
    telefono       text    not null check (telefono ~ '^[0-9]{7,10}$'),
    direccion      text    not null check (char_length(trim(direccion)) >= 5),
    tipo_servicio  text    not null check (tipo_servicio in ('noche', 'dia')),
    cantidad       integer not null check (cantidad between 1 and 30),
    metodo_pago    text    not null,
    instrucciones  text    not null default '',
    total          integer not null check (total >= 0),
    creada_en      timestamptz not null default now()
);

-- 3. Seguridad 
alter table public.fincas   enable row level security;
alter table public.reservas enable row level security;

-- permiten volver a ejecutar este archivo sin errores
drop policy if exists "fincas_leer"     on public.fincas;
drop policy if exists "fincas_crear"    on public.fincas;
drop policy if exists "fincas_editar"   on public.fincas;
drop policy if exists "fincas_eliminar" on public.fincas;
drop policy if exists "reservas_crear"  on public.reservas;

-- Fincas: la página puede leer, crear, editar y eliminar (no hay login en el proyecto)
create policy "fincas_leer"     on public.fincas for select to anon using (true);
create policy "fincas_crear"    on public.fincas for insert to anon with check (true);
create policy "fincas_editar"   on public.fincas for update to anon using (true) with check (true);
create policy "fincas_eliminar" on public.fincas for delete to anon using (true);

-- Reservas: la página solo puede CREAR. Nadie puede leerlas con la clave pública,
-- así los datos personales de los clientes (correo, teléfono, dirección) quedan protegidos.
create policy "reservas_crear" on public.reservas for insert to anon with check (true);

